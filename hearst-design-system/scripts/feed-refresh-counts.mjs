import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const statePath = resolve("src/components/hearst-feed-source-index.json");

async function readState() {
  try {
    return JSON.parse(await readFile(statePath, "utf8"));
  } catch (error) {
    if (error.code === "ENOENT") return { version: 1, destinations: {} };
    throw error;
  }
}

function normalizeSourceUrl(value) {
  if (!value) return "";

  try {
    const url = new URL(value.trim());
    url.hash = "";
    if (url.pathname.length > 1) url.pathname = url.pathname.replace(/\/+$/, "");
    return url.toString();
  } catch {
    return value.trim();
  }
}

function urlsByBrand(stories) {
  const result = {};

  for (const story of stories) {
    const sourceUrl = normalizeSourceUrl(story.sourceUrl);
    if (!sourceUrl || !story.brandSlug) continue;
    const urls = new Set(result[story.brandSlug] ?? []);
    urls.add(sourceUrl);
    result[story.brandSlug] = [...urls].sort();
  }

  return result;
}

async function loadFirstRunBaseline(outputPath, storiesExportName) {
  try {
    const source = await readFile(resolve(outputPath), "utf8");
    const generatedLine = source.match(/^\/\/ Generated by .*? on (.+)\.$/m)?.[1];
    const generatedAt = generatedLine && Number.isFinite(Date.parse(generatedLine))
      ? new Date(generatedLine).toISOString()
      : null;
    const marker = `export const ${storiesExportName}`;
    const exportStart = source.indexOf(marker);

    if (exportStart < 0) return { refreshedAt: generatedAt, sourceUrlsByBrand: {} };

    const assignment = source.indexOf("=", exportStart);
    const arrayStart = source.indexOf("[", assignment + 1);
    const arrayEnd = source.indexOf("\n];", arrayStart);
    if (arrayStart < 0 || arrayEnd < 0) {
      return { refreshedAt: generatedAt, sourceUrlsByBrand: {} };
    }

    const previousStories = JSON.parse(source.slice(arrayStart, arrayEnd + 2));
    return {
      refreshedAt: generatedAt,
      sourceUrlsByBrand: urlsByBrand(previousStories),
    };
  } catch (error) {
    if (error.code === "ENOENT") return { refreshedAt: null, sourceUrlsByBrand: {} };
    throw error;
  }
}

export async function loadPreviousFeedSnapshot(destination, outputPath, storiesExportName) {
  const state = await readState();
  const savedSnapshot = state.destinations?.[destination];
  if (savedSnapshot?.refreshedAt) {
    return {
      refreshedAt: savedSnapshot.refreshedAt,
      sourceUrlsByBrand: savedSnapshot.sourceUrlsByBrand ?? {},
      baselineAvailable: true,
    };
  }

  const firstRunBaseline = await loadFirstRunBaseline(outputPath, storiesExportName);
  return {
    ...firstRunBaseline,
    baselineAvailable: Boolean(firstRunBaseline.refreshedAt),
  };
}

export function countNewStoriesSincePreviousRefresh(stories, previousSnapshot) {
  const counts = {};
  if (!previousSnapshot.baselineAvailable) return { counts, baselineAvailable: false };

  const refreshedAt = Date.parse(previousSnapshot.refreshedAt);
  if (!Number.isFinite(refreshedAt)) return { counts, baselineAvailable: false };

  const previousUrlsByBrand = Object.fromEntries(
    Object.entries(previousSnapshot.sourceUrlsByBrand ?? {}).map(([brandSlug, urls]) => [
      brandSlug,
      new Set(urls.map(normalizeSourceUrl)),
    ]),
  );
  const seenThisRefresh = new Set();
  const now = Date.now();

  for (const story of stories) {
    const sourceUrl = normalizeSourceUrl(story.sourceUrl);
    const publishedAt = Date.parse(story.publishedAt ?? "");
    const identity = `${story.brandSlug}:${sourceUrl}`;

    if (
      !story.brandSlug
      || !sourceUrl
      || !Number.isFinite(publishedAt)
      || publishedAt <= refreshedAt
      || publishedAt > now
      || previousUrlsByBrand[story.brandSlug]?.has(sourceUrl)
      || seenThisRefresh.has(identity)
    ) {
      continue;
    }

    seenThisRefresh.add(identity);
    counts[story.brandSlug] = (counts[story.brandSlug] ?? 0) + 1;
  }

  return { counts, baselineAvailable: true };
}

export async function saveFeedRefreshSnapshot({
  destination,
  refreshedAt,
  previousRefreshedAt,
  stories,
  brandNamesBySlug,
  newStoryCountsByBrand,
  baselineAvailable,
}) {
  const state = await readState();
  state.version = 1;
  state.destinations ??= {};
  state.destinations[destination] = {
    previousRefreshedAt,
    refreshedAt,
    baselineAvailable,
    brandNamesBySlug,
    sourceUrlsByBrand: urlsByBrand(stories),
    newStoryCountsByBrand,
  };

  await mkdir(dirname(statePath), { recursive: true });
  await writeFile(statePath, `${JSON.stringify(state, null, 2)}\n`, "utf8");
}

export async function writeDailyStoryCountsReport() {
  const state = await readState();
  const destinationOrder = [
    ["lifestyle", "Lifestyle"],
    ["autos", "Autos"],
    ["flux", "Fashion & Luxury"],
    ["ew", "Enthusiast & Wellness"],
  ];
  const snapshots = destinationOrder
    .map(([key, name]) => [name, state.destinations?.[key]])
    .filter(([, snapshot]) => snapshot);
  const refreshedAt = snapshots
    .map(([, snapshot]) => Date.parse(snapshot.refreshedAt))
    .filter(Number.isFinite)
    .sort((a, b) => b - a)[0];
  const refreshedLabel = refreshedAt
    ? new Date(refreshedAt).toISOString().replace("T", " ").replace(/\.\d+Z$/, " UTC")
    : "Unknown";
  const lines = [
    "# Daily Hearst Story Counts",
    "",
    `**Latest refresh:** ${refreshedLabel}`,
    "",
    "Counts include distinct source URLs published since the previous successful feed refresh. They are calculated from deduplicated source candidates before the app’s inventory selection caps, so destination totals are not limited to 200. The app’s feed inventory caps remain unchanged.",
    "",
    "If the previous source URL index is unavailable, the first run uses the last generated feed timestamp and reports that baseline in the section heading.",
    "",
  ];

  let overallTotal = 0;
  let allBaselinesAvailable = true;

  for (const [destinationName, snapshot] of snapshots) {
    const counts = snapshot.newStoryCountsByBrand ?? {};
    const brandNames = snapshot.brandNamesBySlug ?? {};
    const previousRefreshLabel = snapshot.previousRefreshedAt
      ? new Date(snapshot.previousRefreshedAt).toISOString().replace("T", " ").replace(/\.\d+Z$/, " UTC")
      : "no prior baseline";
    const slugs = Object.keys(brandNames);
    const total = Object.values(counts).reduce((sum, count) => sum + (count ?? 0), 0);
    overallTotal += total;
    allBaselinesAvailable &&= Boolean(snapshot.baselineAvailable);

    lines.push(
      `## ${destinationName} — ${snapshot.baselineAvailable ? total : "baseline unavailable"} new stories since ${previousRefreshLabel}`,
      "",
      "| Brand | New stories |",
      "|---|---:|",
    );

    for (const brandSlug of slugs) {
      const count = snapshot.baselineAvailable ? (counts[brandSlug] ?? 0) : "N/A";
      lines.push(`| ${brandNames[brandSlug]} | ${count} |`);
    }

    lines.push(`| **Total** | **${snapshot.baselineAvailable ? total : "N/A"}** |`, "");
  }

  lines.push(
    "## Overall total",
    "",
    `**${allBaselinesAvailable ? overallTotal : "N/A until all source baselines are available"} new stories**`,
    "",
    "New stories are counted by brand when their source URL was absent from the previous refresh and their source publication time is newer than that refresh. Existing catalog size limits do not affect this count.",
    "",
  );

  await writeFile(resolve("daily-story-counts.md"), lines.join("\n"), "utf8");
}
